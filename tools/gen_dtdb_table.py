#!/usr/bin/env python3
"""Generate the Fairhead & Bretagnon TDB-TT coefficient table.

The table is the 787-term series implemented by ERFA `dtdb.c` (the same
series is in IAU SOFA `iauDtdb`), from:

    Fairhead, L., & Bretagnon, P., Astron. Astrophys. 229, 240-247 (1990).

This script extracts the coefficients and writes a Rust constant table.
It is offline tooling: not built by Cargo, never a runtime dependency.

Usage:
    python tools/gen_dtdb_table.py --out src/dtdb_table.rs
    python tools/gen_dtdb_table.py --src target/dtdb.c --out src/dtdb_table.rs
    python tools/gen_dtdb_table.py --url https://mirror.example/dtdb.c
    python tools/gen_dtdb_table.py --insecure   # only if a custom CA is unavailable

The download endpoint can also be set once with the ``STKCRAFT_DTDB_URL``
environment variable; ``--url`` wins over the environment. Any mirror is
accepted because the SHA-256 of the payload is still verified.

The generated file is committed so the crate builds without network access.
The source commit and SHA-256 are pinned; a mismatch is an error.
Coefficient data is factual; attribution is recorded in ATTRIBUTION.md.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import ssl
import urllib.request
from pathlib import Path

SOURCE_COMMIT = "1a8044cde5b7763295d472a6443387239127c6c8"
SOURCE_URL = f"https://raw.githubusercontent.com/liberfa/erfa/{SOURCE_COMMIT}/src/dtdb.c"
ENV_URL = "STKCRAFT_DTDB_URL"
EXPECTED_SHA256 = "228bd7c7c1c88dda44c29a076f289c968f64d77a2dc389138b03ab5d1d442105"
EXPECTED = 787


def read_source(path: str | None, insecure: bool, url: str) -> str:
    if path:
        payload = Path(path).read_bytes()
    else:
        context = (
            ssl._create_unverified_context()
            if insecure
            else ssl.create_default_context()
        )
        request = urllib.request.Request(url, headers={"User-Agent": "stkcraft-time"})
        with urllib.request.urlopen(request, context=context, timeout=60) as response:
            payload = response.read()

    digest = hashlib.sha256(payload).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(
            "dtdb.c SHA-256 mismatch: "
            f"expected {EXPECTED_SHA256}, got {digest}"
        )

    return payload.decode("utf-8")


def extract(text: str) -> list[list[str]]:
    marker = "static const double fairhd[787][3] = {"
    start = text.find(marker)
    if start < 0:
        raise SystemExit("could not find the fairhd table")

    body_start = text.find("{", start)
    body_end = text.find("};", body_start)
    body = text[body_start + 1 : body_end]

    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)

    rows = []
    for match in re.finditer(r"\{([^{}]+)\}", body):
        parts = [part.strip() for part in match.group(1).split(",") if part.strip()]
        if len(parts) != 3:
            raise SystemExit(f"unexpected row: {match.group(0)!r}")
        rows.append(parts)

    if len(rows) != EXPECTED:
        raise SystemExit(f"expected {EXPECTED} rows, found {len(rows)}")

    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", help="local dtdb.c (default: download)")
    parser.add_argument("--out", default="src/dtdb_table.rs")
    parser.add_argument(
        "--url",
        default=os.environ.get(ENV_URL, SOURCE_URL),
        help=f"source URL when --src is absent (default: ${ENV_URL} or pinned ERFA URL)",
    )
    parser.add_argument(
        "--insecure",
        action="store_true",
        help="skip TLS certificate verification (only with a custom CA setup)",
    )
    args = parser.parse_args()

    rows = extract(read_source(args.src, args.insecure, args.url))

    lines = [
        "//! Generated by `tools/gen_dtdb_table.py`. Do not edit by hand.",
        "//!",
        "//! Fairhead & Bretagnon (1990) TDB-TT series, 787 terms, amplitudes",
        "//! in seconds, frequencies in radians per Julian millennium, phases in",
        "//! radians. Extracted from ERFA `dtdb.c` (IAU SOFA `iauDtdb`).",
        f"//! Source commit: {SOURCE_COMMIT}",
        f"//! Source SHA-256: {EXPECTED_SHA256}",
        "",
        f"pub(crate) static FAIRHD: [[f64; 3]; {EXPECTED}] = [",
    ]
    for row in rows:
        lines.append(f"    [{row[0]}, {row[1]}, {row[2]}],")
    lines.append("];")
    lines.append("")

    out = Path(args.out)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({len(rows)} terms)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
