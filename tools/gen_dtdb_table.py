#!/usr/bin/env python3
"""Generate the Fairhead & Bretagnon TDB-TT coefficient table.

The table is the 787-term series implemented by ERFA `dtdb.c` (the same
series is in IAU SOFA `iauDtdb`), from:

    Fairhead, L., & Bretagnon, P., Astron. Astrophys. 229, 240-247 (1990).

This script extracts the coefficients and writes a Rust constant table.
It is offline tooling: not built by Cargo, never a runtime dependency.

Usage:
    python tools/gen_dtdb_table.py --out src/dtdb_table.rs
    python tools/gen_dtdb_table.py --src target/dtdb.c --out src/dtdb_table.rs

The generated file is committed so the crate builds without network access.
Coefficient data is factual; attribution is recorded in ATTRIBUTION.md.
"""

from __future__ import annotations

import argparse
import re
import ssl
import urllib.request
from pathlib import Path

SOURCE_URL = "https://raw.githubusercontent.com/liberfa/erfa/master/src/dtdb.c"
EXPECTED = 787


def read_source(path: str | None) -> str:
    if path:
        return Path(path).read_text(encoding="utf-8")

    context = ssl._create_unverified_context()
    request = urllib.request.Request(SOURCE_URL, headers={"User-Agent": "stkcraft-time"})
    with urllib.request.urlopen(request, context=context, timeout=60) as response:
        return response.read().decode("utf-8")


def extract(text: str) -> list[list[str]]:
    marker = "static const double fairhd[787][3] = {"
    start = text.find(marker)
    if start < 0:
        raise SystemExit("could not find the fairhd table")

    body_start = text.find("{", start)
    body_end = text.find("};", body_start)
    body = text[body_start + 1 : body_end]

    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)

    rows = []
    for match in re.finditer(r"\{([^{}]+)\}", body):
        parts = [part.strip() for part in match.group(1).split(",") if part.strip()]
        if len(parts) != 3:
            raise SystemExit(f"unexpected row: {match.group(0)!r}")
        rows.append(parts)

    if len(rows) != EXPECTED:
        raise SystemExit(f"expected {EXPECTED} rows, found {len(rows)}")

    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", help="local dtdb.c (default: download)")
    parser.add_argument("--out", default="src/dtdb_table.rs")
    args = parser.parse_args()

    rows = extract(read_source(args.src))

    lines = [
        "//! Generated by `tools/gen_dtdb_table.py`. Do not edit by hand.",
        "//!",
        "//! Fairhead & Bretagnon (1990) TDB-TT series, 787 terms, amplitudes",
        "//! in seconds, frequencies in radians per Julian millennium, phases in",
        "//! radians. Extracted from ERFA `dtdb.c` (IAU SOFA `iauDtdb`).",
        "",
        f"pub(crate) static FAIRHD: [[f64; 3]; {EXPECTED}] = [",
    ]
    for row in rows:
        lines.append(f"    [{row[0]}, {row[1]}, {row[2]}],")
    lines.append("];")
    lines.append("")

    out = Path(args.out)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({len(rows)} terms)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
